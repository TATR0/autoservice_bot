"""
policy.py — документы, к которым отсылают галочки согласия.

Три страницы, и все три собираются кодом, а не лежат готовыми файлами:

  /privacy — как обрабатываются данные клиента. Оператор у каждой формы свой:
             данные собирает тот автосервис, в который записываются, и называть
             его надо по имени, с телефоном и адресом.
  /terms   — правила пользования записью. Тоже про конкретный сервис: услуги
             оказывает он, а бот только передаёт заявку.
  /offer   — оферта на подписку. Сторона здесь уже не автосервис, а владелец
             бота, и цены в ней — настоящие, из config.PLANS.

Всё, что подставляется, подставляется настоящим. Обещание стереть данные через
год, когда чистка выключена, хуже отсутствия обещания: первое — неправда,
второе — всего лишь умолчание.
"""

from __future__ import annotations

from html import escape
from typing import Any, Mapping

import config
from validators import format_phone

# Ровно те поля, которые стирает db.anonymize_old_requests и /forget_me.
# Список здесь и список там обязаны совпадать: расходятся — политика врёт
COLLECTED = "имя, телефон, марка и модель машины, госномер, комментарий"

# Дата редакции оферты. Руками: она меняется, когда меняется текст, а не
# когда страницу открыли. Подставлять сюда сегодняшнее число — выдавать
# вчерашний договор за сегодняшний
OFFER_REVISION = "24 сентября 2026 года"

_STYLE = """
  body { margin: 0; padding: 20px 18px 48px; max-width: 700px;
         font: 15px/1.6 -apple-system, "Segoe UI", Roboto, sans-serif;
         color: #1c1c1e; background: #fff; }
  h1 { font-size: 20px; margin: 0 0 20px; }
  h2 { font-size: 16px; margin: 28px 0 8px; }
  ul { margin: 8px 0; padding-left: 20px; }
  p { margin: 8px 0; }
  code { background: #f1f1f4; border-radius: 4px; padding: 1px 5px; }
  table { border-collapse: collapse; margin: 10px 0; }
  td { padding: 4px 18px 4px 0; }
  .aside { color: #6b6b70; font-size: 13px; }
  @media (prefers-color-scheme: dark) {
    body { color: #e9e9ea; background: #17181a; }
    code { background: #2a2b2e; }
    .aside { color: #9a9a9f; }
  }
"""


def _page(title: str, body: str) -> str:
    """Общая обёртка: у трёх документов один вид и один набор мета-тегов."""
    return (
        '<!DOCTYPE html>\n<html lang="ru">\n<head>\n'
        '<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{escape(title)}</title>\n"
        f"<style>{_STYLE}</style>\n"
        f"</head>\n<body>\n<h1>{escape(title)}</h1>\n{body}\n</body>\n</html>\n"
    )


def _days_word(days: int) -> str:
    if days % 100 in range(11, 15):
        return "дней"
    return {1: "день", 2: "дня", 3: "дня", 4: "дня"}.get(days % 10, "дней")


def _hours_word(hours: int) -> str:
    if hours % 100 in range(11, 15):
        return "часов"
    return {1: "час", 2: "часа", 3: "часа", 4: "часа"}.get(hours % 10, "часов")


def _service_name(service: Mapping[str, Any] | None) -> str:
    return escape(str((service or {}).get("service_name") or ""))


def _contacts(service: Mapping[str, Any] | None) -> str:
    """Телефон и адрес сервиса списком. Пусто — ничего, а не пустые строки."""
    if not service:
        return ""
    phone = escape(format_phone(str(service.get("service_number") or "")))
    where = ", ".join(
        escape(str(service.get(field) or ""))
        for field in ("city", "location_service")
        if service.get(field)
    )
    lines = []
    if phone:
        lines.append(f"<li>Телефон: {phone}</li>")
    if where:
        lines.append(f"<li>Адрес: {where}</li>")
    return f"<ul>{''.join(lines)}</ul>" if lines else ""


def _operator(service: Mapping[str, Any] | None) -> str:
    """Кто оператор: конкретный сервис или, если его не назвали, тот, куда записываются."""
    if not service:
        return (
            "<p>Оператор ваших данных — автосервис, в который вы записываетесь. "
            "Его название, телефон и адрес видны в карточке сервиса, там же, "
            "где вы выбирали услугу.</p>"
        )
    return f"<p>Оператор ваших данных — <b>{_service_name(service)}</b>.</p>" \
           + _contacts(service)


def _storage(retention_days: int) -> str:
    if retention_days > 0:
        return (
            f"<p>{COLLECTED.capitalize()} хранятся "
            f"<b>{retention_days} {_days_word(retention_days)}</b> с момента "
            "обращения, после чего стираются из заявки сами. У сервиса остаётся "
            "обезличенная запись: дата, услуга и то, что обращение было. "
            "По ней вас не найти.</p>"
        )
    # Молчать об этом нельзя: человеку важно знать, что срок не задан, —
    # тогда он воспользуется правом стереть данные сам, не дожидаясь чистки
    return (
        f"<p>{COLLECTED.capitalize()} хранятся, пока вы не попросите их удалить: "
        "автоматического срока сервис не установил. Как удалить — ниже.</p>"
    )


def render(service: Mapping[str, Any] | None = None,
           retention_days: int | None = None) -> str:
    """Согласие на обработку данных. Всё из базы — через escape."""
    if retention_days is None:
        retention_days = config.PII_RETENTION_DAYS

    return _page("Обработка персональных данных", f"""
{_operator(service)}

<h2>Что собирается</h2>
<p>Из формы записи: {COLLECTED}, а также выбранные услуги и время визита.</p>
<p>Из Telegram: ваш числовой идентификатор, имя и @username — их передаёт сам
Telegram, когда вы пишете боту. Телефон сохраняется, только если вы отправили
его боту сами, чтобы не вводить заново в следующий раз.</p>

<h2>Зачем</h2>
<p>Чтобы сервис принял запись, подтвердил её, позвонил вам при необходимости и
напомнил о визите. Ни для чего другого эти данные не используются: рассылок нет,
третьим лицам они не передаются, не продаются и не публикуются.</p>

<h2>Где хранится</h2>
<p>На сервере, который обслуживает бот записи. Владелец бота хранит данные по
поручению автосервиса и своих целей в них не имеет: он их не читает, не
передаёт и не использует. Доступ к вашим заявкам есть у сотрудников сервиса,
которых назначил управляющий.</p>

<h2>Сколько хранится</h2>
{_storage(retention_days)}

<h2>Чем вы соглашаетесь</h2>
<p>Галочка под формой записи — и есть согласие: на сбор, хранение, уточнение и
удаление перечисленного выше, ради записи в сервис и связи с вами по ней.
Согласие добровольное — без него запись не отправится, потому что принять её
без имени и телефона нельзя.</p>

<h2>Как отозвать согласие и удалить данные</h2>
<p>Отправьте боту команду <code>/forget_me</code>. Из ваших заявок пропадут
{COLLECTED}; сохранённый телефон и профиль в боте тоже сотрутся. Отменить это
нельзя, и это не требует ничьего разрешения.</p>
<p>Одно исключение: пока у вас есть незакрытая заявка, данные по ней не
стираются — по ней вас ждут. Отмените запись или дождитесь визита, и повторите
команду.</p>
<p>Можно и просто позвонить в сервис по телефону выше и попросить удалить
данные — результат тот же.</p>
""")


def render_terms(service: Mapping[str, Any] | None = None) -> str:
    """Правила пользования записью — вторая галочка под формой."""
    if service:
        who = (f"<p>Услуги оказывает <b>{_service_name(service)}</b> — "
               "с ним у вас и будут отношения по ремонту.</p>"
               + _contacts(service))
    else:
        who = ("<p>Услуги оказывает автосервис, в который вы записываетесь, — "
               "с ним у вас и будут отношения по ремонту. Название, телефон и "
               "адрес видны в его карточке.</p>")

    hours = config.APPOINTMENT_REMINDER_HOURS
    reminder = (
        f"<p>За {hours} {_hours_word(hours)} до визита бот напомнит о записи "
        "сообщением.</p>"
        if hours > 0 else ""
    )

    return _page("Правила пользования записью", f"""
<p>Бот записывает вас в автосервис: показывает свободное время, передаёт заявку
и приносит ответ. Пользование им бесплатно, счетов он не выставляет и денег за
ремонт не принимает.</p>

<h2>Кто что делает</h2>
{who}
<p>Бот — только способ записаться. Цены, сроки, объём работ, гарантия и качество
ремонта — на стороне сервиса; всё, что написано в его карточке и в списке услуг,
написал он сам. Разногласия по работам решаются с ним, по телефону выше.</p>

<h2>Как проходит запись</h2>
<ul>
  <li>Вы выбираете услуги, день и время и отправляете заявку.</li>
  <li>Заявка приходит сервису, и он подтверждает её или отказывает — ответ
      придёт вам в бот. Выбранное время держится за вами до ответа, но пока
      сервис не подтвердил, визит не назначен.</li>
  <li>Сервис может позвонить, чтобы уточнить, что случилось с машиной.</li>
</ul>
{reminder}

<h2>Что нужно от вас</h2>
<ul>
  <li>Настоящие имя, телефон и номер машины: по ним вас узнают и вам позвонят.
      Чужие данные вводить нельзя.</li>
  <li>Приехать в назначенное время или отменить запись заранее. Отменяется она
      кнопкой под заявкой в боте или звонком в сервис; список ваших записей —
      в боте, кнопка «📋 Мои заявки».</li>
</ul>
<p>Заявки без намерения приехать занимают чужое время: сервис вправе отказать
в записи тому, кто не приезжает.</p>

<h2>Чего бот не делает</h2>
<p>Не оказывает ремонт, не принимает оплату за него, не проверяет цены и
обещания сервиса и не отвечает за них. Он может быть недоступен — из-за работ,
сбоя или неполадок в Telegram; в такие минуты запись не отправится, и сервису
надо просто позвонить.</p>

<h2>Ваши данные</h2>
<p>Что собирается, зачем, надолго ли и как это стереть — в документе
«Обработка персональных данных», по соседней ссылке под формой.</p>
""")


def _price_table() -> str:
    rows = "".join(
        f"<tr><td>{escape(plan.label)}</td>"
        f"<td>{escape(config.plan_price(plan))}</td></tr>"
        for plan in config.PLANS
    )
    return f"<table>{rows}</table>"


def _payment_order() -> str:
    if config.PAYMENT_METHOD == config.PAYMENT_YOOMONEY:
        return (
            "<p>Оплата — переводом через ЮMoney по ссылке из бота. Сумма и "
            "назначение платежа подставлены заранее, менять их не нужно: по "
            "ним платёж и опознаётся. Дни начисляются после того, как ЮMoney "
            "подтвердит перевод; если подтверждение почему-то не дошло, дни "
            "начисляет исполнитель вручную — напишите ему.</p>"
        )
    return (
        "<p>Оплата — счётом Telegram в звёздах, прямо в боте. Дни начисляются "
        "сразу после оплаты, без участия человека.</p>"
    )


def _expiry_clause() -> str:
    if config.SUBSCRIPTION_ENFORCED:
        return (
            "<p>Кончился оплаченный срок — сервис пропадает из поиска и "
            "перестаёт принимать новые записи. Данные при этом не удаляются: "
            "оплатите — всё вернётся на место вместе с историей.</p>"
        )
    # Пока отключение не введено, обещать его в договоре нельзя: заказчик
    # прочтёт про санкцию, которой нет, и не поверит остальному тексту
    return (
        "<p>Оплаченный срок считается, но отключение за неоплату пока не "
        "введено: сервис продолжает работать и после окончания срока. Когда "
        "отключение введут, об этом предупредят заранее, в боте.</p>"
    )


def render_offer() -> str:
    """
    Оферта на подписку. Стороны — владелец бота и автосервис, не клиент.

    Вызывать только при config.offer_published(): без имени, ИНН и адреса для
    претензий это не договор, а текст.
    """
    provider = escape(config.OFFER_PROVIDER)
    inn = escape(config.OFFER_INN)
    contact = escape(config.OFFER_CONTACT)
    trial = (
        f"<p>Первые {config.TRIAL_DAYS} {_days_word(config.TRIAL_DAYS)} — "
        "бесплатно, чтобы посмотреть, подходит ли бот. Пробный период даётся "
        "один раз: второй сервис того же управляющего оплачивается с первого "
        "дня.</p>"
        if config.TRIAL_DAYS > 0 else ""
    )

    return _page("Оферта на подписку", f"""
<p class="aside">Редакция от {OFFER_REVISION}</p>

<p>Это предложение заключить договор на пользование ботом записи в автосервис.
Оно адресовано автосервисам и их управляющим, а не клиентам, которые
записываются, — тем платить не за что.</p>
<p>Согласие с офертой — оплата подписки. Оплатили — договор заключён на
условиях ниже, в той редакции, что была опубликована здесь на момент оплаты.</p>

<h2>Стороны</h2>
<p>Исполнитель — {provider}, ИНН {inn}. Связь по любому вопросу, включая
претензии: {contact}.</p>
<p>Заказчик — автосервис в лице управляющего, который зарегистрировал сервис в
боте и оплатил подписку.</p>

<h2>Что входит в подписку</h2>
<ul>
  <li>Карточка сервиса в поиске бота: город, адрес, телефон, услуги и цены.</li>
  <li>Форма записи для клиентов и расписание с рабочими часами и выходными.</li>
  <li>Приём заявок, уведомления сотрудникам, история и статусы заявок.</li>
  <li>Напоминания клиентам о визите.</li>
</ul>
<p>Бот работает круглосуточно, кроме перерывов на обслуживание и сбоев —
своих, у хостинга или у Telegram.</p>

<h2>Сроки и цены</h2>
{trial}
{_price_table()}
<p>Оплаченные дни прибавляются к текущему сроку, а не начинают его заново:
платить заранее не значит терять остаток. Цена закрепляется за уже оплаченным
сроком; новая цена действует только для следующих оплат.</p>

<h2>Как платить</h2>
{_payment_order()}
<p>Услуга считается оказанной по дням: каждый оплаченный день, когда бот
доступен, — оказанный день.</p>

<h2>Возврат</h2>
<p>Передумали — напишите {contact}. Неиспользованные дни возвращаются деньгами:
звёзды Telegram возвращает тем же платежом, перевод возвращается обратным
переводом. Срок — десять дней с обращения. Использованные дни не
возвращаются.</p>

<h2>Данные клиентов</h2>
<p>Имена, телефоны и госномера, которые клиенты оставляют в форме, принадлежат
заказчику: он их оператор, он отвечает перед клиентом и он решает, сколько их
хранить. Исполнитель обрабатывает эти данные <b>по поручению заказчика</b> и
только ради работы бота: хранит, показывает сотрудникам сервиса, обезличивает
по сроку и удаляет по требованию. Исполнитель не использует их в своих целях,
не передаёт третьим лицам и не продаёт.</p>
<p>Поручение действует, пока действует подписка. Заказчик, со своей стороны,
обязуется собирать данные с согласия клиента — бот берёт согласие сам, в форме
записи, и показывает клиенту, что и сколько хранится.</p>

<h2>Ответственность</h2>
<p>Исполнитель отвечает за работу бота. Он не участвует в ремонте, не проверяет
цены и обещания сервиса и не отвечает за них перед клиентами: услуги оказывает
заказчик. Ответственность исполнителя ограничена стоимостью оплаченного
периода — это всё, что он получил.</p>

<h2>Окончание подписки</h2>
{_expiry_clause()}
<p>Удалить сервис и всё, что с ним связано, можно по письму на {contact}.</p>

<h2>Изменения</h2>
<p>Новая редакция публикуется на этой странице и действует для оплат после
публикации. Уже оплаченный срок она не меняет.</p>
""")
